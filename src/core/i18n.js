class I18n {
    constructor() {
        this.currentLang = 'es';
        this.subscribers = [];
        this.init();
    }

    init() {
        const savedLang = localStorage.getItem('appLang');
        if (savedLang) {
            this.currentLang = savedLang;
        } else {
            // Auto detect from OS
            const browserLang = navigator.language || navigator.userLanguage;
            if (browserLang.toLowerCase().startsWith('en')) {
                this.currentLang = 'en';
            } else {
                this.currentLang = 'es';
            }
        }
    }

    setLanguage(lang) {
        if (dictionary[lang]) {
            this.currentLang = lang;
            localStorage.setItem('appLang', lang);
            // Hard reload para reiniciar la DB offline estática (catalogo.json vs catalogo_en.json)
            location.reload();
        }
    }

    getLanguage() {
        return this.currentLang;
    }

    t(key) {
        const text = dictionary[this.currentLang][key];
        return text !== undefined ? text : key;
    }

    updateDOM() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            // If the element has strong tags or html, we set innerHTML, else textContent
            if (el.innerHTML.includes('<') && !el.innerHTML.includes('<svg')) {
                el.innerHTML = this.t(key);
            } else {
                // To avoid destroying SVG icons inside buttons, we only replace the text node
                // Or if it's a simple span, textContent is fine.
                if (['SPAN', 'P', 'H3', 'LABEL', 'BUTTON', 'A', 'DIV'].includes(el.tagName)) {
                    el.innerHTML = this.t(key);
                }
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.setAttribute('placeholder', this.t(key));
        });
    }

    subscribe(callback) {
        this.subscribers.push(callback);
    }

    notifySubscribers() {
        this.subscribers.forEach(cb => cb());
    }
}

export const i18n = new I18n();
